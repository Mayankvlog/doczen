export const GEO_KEYWORD_COUNT =
  GEO_TOPICS.length *
  GEO_STARTERS.length *
  GEO_CONTEXTS.length *
  GEO_MODIFIERS.length *
  GEO_AUDIENCES.length *
  GEO_LOCATIONS.length *
  GEO_ASSISTANTS.length;

export const MIN_GEO_KEYWORDS = 160_000_000_000;

if (GEO_KEYWORD_COUNT < MIN_GEO_KEYWORDS) {
  throw new Error(`The GEO keyword catalog must contain at least ${MIN_GEO_KEYWORDS} keywords.`);
}

export function* iterateGeoKeywords(limit = GEO_KEYWORD_COUNT) {
  if (!Number.isSafeInteger(limit) || limit < 0) {
    throw new TypeError('The GEO keyword limit must be a non-negative safe integer.');
  }

  if (limit === 0) return;

  const seen = new Set();

  for (const topic of GEO_TOPICS) {
    for (const starter of GEO_STARTERS) {
      for (const context of GEO_CONTEXTS) {
        for (const modifier of GEO_MODIFIERS) {
          for (const audience of GEO_AUDIENCES) {
            for (const location of GEO_LOCATIONS) {
              for (const assistant of GEO_ASSISTANTS) {
                const keyword = [starter, topic, context, modifier, audience, location, assistant]
                  .filter(Boolean)
                  .join(' ')
                  .replace(/\s+/g, ' ')
                  .trim();

                if (seen.has(keyword)) continue;
                seen.add(keyword);
                yield keyword;
                if (seen.size >= limit) return;
              }
            }
          }
        }
      }
    }
  }
}

export function generateGeoKeywords(limit = 120) {
  return Array.from(iterateGeoKeywords(Math.min(limit, GEO_KEYWORD_COUNT)));
}

export function getGeoKeywordSample(limit = 30) {
  return generateGeoKeywords(Math.min(limit, GEO_KEYWORD_COUNT));
}
